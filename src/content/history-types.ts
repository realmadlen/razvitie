export interface HistoryEvent {
  /** 'h' + год, например 'h1941'; если в году два события — 'h1941b' */
  id: string
  year: number
  /** Для событий-периодов (война, блокада) */
  yearEnd?: number
  /** Точная дата, если её принято знать: '22 июня' */
  date?: string
  /** Коротко, как в учебнике: 'Начало Великой Отечественной войны' */
  title: string
  /** 1–2 предложения: что случилось и почему это важно */
  detail: string
  /** Эпоха: 'Древняя Русь', 'Российская империя', 'СССР' … */
  era: string
  /** Короткая простая ассоциация, до 12 слов. Нет хорошей — не заполнять */
  mnemonic?: string
}

export interface Ruler {
  /** 'r-' + латиница: 'r-peter1', 'r-stalin' */
  id: string
  /** Полное имя: 'Пётр I Великий' */
  name: string
  /** Как называем в вопросах: 'Пётр I' */
  short: string
  /** 'князь', 'великий князь', 'царь', 'императрица', 'генсек', 'президент' … */
  title: string
  /** Годы у власти */
  from: number
  to: number
  /** Чем известен — без имени, до 90 знаков: 'Основал Петербург и сделал Россию империей' */
  known: string
  /** id прямого предшественника из этого же списка, только если власть перешла сразу от него */
  prev?: string
  /** Короткая простая ассоциация, до 12 слов. Нет хорошей — не заполнять */
  mnemonic?: string
}
