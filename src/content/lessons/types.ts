// Уроки: сначала рассказ, потом проверка. Урок охватывает несколько элементов темы.

export interface LessonPage {
  /** Заголовок экрана (коротко, 2–6 слов) */
  title?: string
  /**
   * Текст экрана. Абзацы разделяются пустой строкой (\n\n).
   * **жирным** выделяется ключевое, что нужно запомнить (год, столица, название).
   */
  text: string
  /** Если экран про конкретный элемент темы — его id; приложение покажет рядом карточку-факт (год, карту, столицу) */
  itemId?: string
  /** Необязательная «пауза-вопрос» после экрана: проверка понимания по только что прочитанному */
  check?: { q: string; options: string[]; correct: number; why?: string }
}

export interface Lesson {
  id: string
  topicId: string
  title: string
  /** Одна строка-приманка: почему интересно */
  teaser: string
  /** Элементы темы, которые урок вводит и которые потом проверяются */
  itemIds: string[]
  pages: LessonPage[]
}
