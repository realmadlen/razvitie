// Задачи по математике и логике. Решаются по желанию в разделе «Задачи».
// Каждая задача создаётся заново и несёт пошаговый разбор именно с её числами.

export type PracticeKind = 'mul' | 'addsub' | 'percent' | 'fraction' | 'square' | 'linear' | 'quadratic' | 'sequence' | 'syllogism'

export interface PracticeTask {
  kind: PracticeKind
  prompt: string
  /** Числовые ответы (для квадратного уравнения — два корня, порядок не важен) */
  answers?: number[]
  /** Подписи полей ввода, если ответов несколько */
  fields?: string[]
  choices?: string[]
  correctChoice?: number
  /** Пошаговый разбор этой задачи */
  steps: string[]
  /** Короткий итог: ответ */
  result: string
  /** Небольшая подсказка — первый шаг без ответа */
  hint: string
}

export interface PracticeInfo {
  kind: PracticeKind
  group: 'math' | 'logic'
  title: string
  sub: string
  /** Как решать такие задачи вообще — шпаргалка */
  theory: string[]
  make: () => PracticeTask
}

const rnd = (a: number, b: number) => Math.floor(Math.random() * (b - a + 1)) + a
const pick = <T,>(xs: T[]) => xs[Math.floor(Math.random() * xs.length)]
/** Число с настоящим знаком минуса */
const n = (v: number) => (v < 0 ? `−${-v}` : String(v))
/** Число в скобках, если отрицательное: 3 × (−2) */
const p = (v: number) => (v < 0 ? `(−${-v})` : String(v))
/** «+ 5» или «− 5» для записи выражений */
const sgn = (v: number) => (v < 0 ? `− ${-v}` : `+ ${v}`)
const gcd = (a: number, b: number): number => (b === 0 ? Math.abs(a) : gcd(b, a % b))
const lcm = (a: number, b: number) => (a * b) / gcd(a, b)

// ——— Умножение в уме ———

function mul(): PracticeTask {
  const a = rnd(12, 98), b = rnd(3, 9)
  const t = Math.floor(a / 10) * 10, u = a % 10
  const steps = u === 0
    ? [`${a} — круглое число: ${a / 10} десятков.`, `${a / 10} × ${b} = ${(a / 10) * b}, и дописываем ноль: ${a * b}.`]
    : [
        `Разложим ${a} на десятки и единицы: ${a} = ${t} + ${u}.`,
        `Умножим десятки: ${t} × ${b}. Это ${t / 10} × ${b} = ${(t / 10) * b}, и дописываем ноль → ${t * b}.`,
        `Умножим единицы: ${u} × ${b} = ${u * b}.`,
        `Сложим два результата: ${t * b} + ${u * b} = ${a * b}.`,
      ]
  return { kind: 'mul', prompt: `${a} × ${b}`, answers: [a * b], steps, result: `${a} × ${b} = ${a * b}`, hint: `Разложите ${a} на ${t} + ${u} и умножьте каждую часть на ${b}.` }
}

// ——— Сложение и вычитание ———

function addsub(): PracticeTask {
  const plus = Math.random() < 0.5
  const a = plus ? rnd(120, 799) : rnd(400, 999), b = plus ? rnd(110, 699) : rnd(105, 399)
  const h = Math.floor(b / 100) * 100, t = Math.floor((b % 100) / 10) * 10, u = b % 10
  const parts = [h, t, u].filter(Boolean)
  const steps = [`Разобьём ${b} на части: ${parts.join(' + ')}. ${plus ? 'Прибавлять' : 'Вычитать'} будем по одной части — так проще удержать в голове.`]
  let cur = a
  for (const part of parts) {
    const nx = plus ? cur + part : cur - part
    steps.push(`${cur} ${plus ? '+' : '−'} ${part} = ${nx}`)
    cur = nx
  }
  steps.push(`Ответ: ${cur}.`)
  if (!plus && u >= 6) steps.push(`Другой приём: ${b} ≈ ${b + (10 - u)}. ${a} − ${b + (10 - u)} = ${a - b - (10 - u)}, и возвращаем лишнее: + ${10 - u} = ${a - b}.`)
  const sign = plus ? '+' : '−'
  return { kind: 'addsub', prompt: `${a} ${sign} ${b}`, answers: [plus ? a + b : a - b], steps, result: `${a} ${sign} ${b} = ${cur}`, hint: `Сначала ${plus ? 'прибавьте' : 'вычтите'} ${h}, потом остальное.` }
}

// ——— Проценты ———

function percent(): PracticeTask {
  const pc = pick([5, 10, 15, 20, 25, 30, 40, 50, 60, 75])
  const base = pick([40, 60, 80, 120, 160, 200, 240, 300, 360, 400, 480, 600, 800, 1200])
  const v = (pc * base) / 100
  if (!Number.isInteger(v)) return percent()
  const ten = base / 10
  const steps = ['Процент — это одна сотая часть. 100% — всё число, 50% — половина, 10% — десятая часть.']
  if (pc === 50) steps.push(`50% — это половина: ${base} : 2 = ${v}.`)
  else if (pc === 25) steps.push(`25% — это четверть, то есть половина от половины.`, `${base} : 2 = ${base / 2}, ещё раз : 2 = ${v}.`)
  else if (pc === 75) steps.push(`75% — это три четверти. Сначала найдём четверть: ${base} : 4 = ${base / 4}.`, `Три четверти: ${base / 4} × 3 = ${v}.`)
  else if (pc === 10) steps.push(`10% — десятая часть: ${base} : 10 = ${v}. Проще всего — убрать у числа последний ноль.`)
  else if (pc === 5) steps.push(`Сначала 10%: ${base} : 10 = ${ten}.`, `5% — это половина от 10%: ${ten} : 2 = ${v}.`)
  else if (pc === 15) steps.push(`15% = 10% + 5%.`, `10% от ${base} = ${ten}.`, `5% — половина от этого: ${ten / 2}.`, `Складываем: ${ten} + ${ten / 2} = ${v}.`)
  else steps.push(`Сначала 10%: ${base} : 10 = ${ten}.`, `${pc}% — это ${pc / 10} ${pc / 10 < 5 ? "раза" : "раз"} по 10%: ${ten} × ${pc / 10} = ${v}.`)
  steps.push(`Проверка формулой: ${base} × ${pc} : 100 = ${v}.`)
  return { kind: 'percent', prompt: `${pc}% от ${base}`, answers: [v], steps, result: `${pc}% от ${base} = ${v}`, hint: `Найдите сначала 10% от ${base} — уберите последний ноль.` }
}

// ——— Дроби ———

function fraction(): PracticeTask {
  const d1 = pick([2, 3, 4, 5, 6]), d2 = pick([2, 3, 4, 6, 8])
  const n1 = rnd(1, d1 - 1), n2 = rnd(1, d2 - 1)
  const L = lcm(d1, d2), k1 = L / d1, k2 = L / d2
  const a1 = n1 * k1, a2 = n2 * k2, num = a1 + a2
  const g = gcd(num, L), rn = num / g, rd = L / g
  const steps = [
    'Складывать дроби можно, только когда у них одинаковый знаменатель — нижнее число. Поэтому сначала приводим их к общему знаменателю.',
    d1 === d2
      ? `Знаменатели уже одинаковые: ${L}.`
      : `Знаменатели ${d1} и ${d2}. Ищем наименьшее число, которое делится и на ${d1}, и на ${d2}: это ${L}.`,
  ]
  if (d1 !== d2) {
    steps.push(k1 === 1 ? `${n1}/${d1} оставляем как есть.` : `${n1}/${d1}: ${L} : ${d1} = ${k1}, умножаем верх и низ на ${k1} → ${a1}/${L}.`)
    steps.push(k2 === 1 ? `${n2}/${d2} оставляем как есть.` : `${n2}/${d2}: ${L} : ${d2} = ${k2}, умножаем верх и низ на ${k2} → ${a2}/${L}.`)
  }
  steps.push(`Теперь складываем только верхние числа, низ не меняется: ${a1}/${L} + ${a2}/${L} = ${num}/${L}.`)
  steps.push(g > 1 ? `Сокращаем: и ${num}, и ${L} делятся на ${g}. Получаем ${rn}/${rd}.` : `Сократить ${num}/${L} нельзя — у чисел нет общего делителя.`)
  if (rn > rd) steps.push(`Это больше единицы: ${rn}/${rd} = ${Math.floor(rn / rd)} целая и ${rn % rd}/${rd}.`)
  return { kind: 'fraction', prompt: `${n1}/${d1} + ${n2}/${d2} = ?/${rd}`, answers: [rn], steps, result: `${n1}/${d1} + ${n2}/${d2} = ${rn}/${rd}`, hint: d1 === d2 ? 'Знаменатели одинаковые — сложите числители.' : `Приведите обе дроби к знаменателю ${L}.` }
}

// ——— Квадрат числа ———

function square(): PracticeTask {
  const v = rnd(11, 29)
  const t = Math.floor(v / 10) * 10, u = v % 10
  const steps = u === 0
    ? [`${v}² = ${v} × ${v} = ${v * v}.`]
    : [
        'Квадрат числа — это число, умноженное само на себя. В уме удобно по формуле (a + b)² = a² + 2·a·b + b².',
        `Разложим: ${v} = ${t} + ${u}, то есть a = ${t}, b = ${u}.`,
        `a² = ${t} × ${t} = ${t * t}.`,
        `2·a·b = 2 × ${t} × ${u} = ${2 * t * u}.`,
        `b² = ${u} × ${u} = ${u * u}.`,
        `Складываем: ${t * t} + ${2 * t * u} + ${u * u} = ${v * v}.`,
      ]
  if (u === 5) steps.push(`Приём для чисел на 5: десятки умножить на следующее число и дописать 25. ${t / 10} × ${t / 10 + 1} = ${(t / 10) * (t / 10 + 1)} → ${v * v}.`)
  return { kind: 'square', prompt: `${v}²`, answers: [v * v], steps, result: `${v}² = ${v * v}`, hint: `Представьте ${v} как ${t} + ${u}.` }
}

// ——— Линейное уравнение ———

function linear(): PracticeTask {
  const a = rnd(2, 9), x = rnd(-6, 12), b = pick([-1, 1]) * rnd(2, 20)
  const c = a * x + b, r = c - b
  const steps = [
    `Решить уравнение — значит найти, чему равен x. Цель: оставить x одного с левой стороны.`,
    `Слева, кроме ${a}x, есть ${b < 0 ? `вычитание ${-b}` : `прибавление ${b}`}. Перенесём это число вправо — при переносе знак меняется на противоположный: ${a}x = ${n(c)} ${sgn(-b)}.`,
    `Посчитаем правую часть: ${n(c)} ${sgn(-b)} = ${n(r)}. Теперь ${a}x = ${n(r)}.`,
    `${a}x означает «${a} умножить на x». Чтобы убрать умножение, делим обе части на ${a}: x = ${n(r)} : ${a} = ${n(x)}.`,
    `Проверка: подставим x = ${n(x)}. ${a} × ${p(x)} ${sgn(b)} = ${n(a * x)} ${sgn(b)} = ${n(c)}. Совпало ✓`,
  ]
  return { kind: 'linear', prompt: `${a}x ${sgn(b)} = ${n(c)}`, answers: [x], steps, result: `x = ${n(x)}`, hint: `Перенесите ${sgn(b).replace(' ', '')} вправо с обратным знаком.` }
}

// ——— Квадратное уравнение ———

function quadratic(): PracticeTask {
  let r1 = rnd(-7, 7), r2 = rnd(-7, 7)
  if (r1 === r2) r2 = r1 + rnd(1, 4)
  if (r1 > r2) [r1, r2] = [r2, r1]
  const b = -(r1 + r2), c = r1 * r2, s = -b
  const bTxt = b === 0 ? '' : b === 1 ? ' + x' : b === -1 ? ' − x' : ` ${sgn(b)}x`
  const cTxt = c === 0 ? '' : ` ${sgn(c)}`
  const prompt = `x²${bTxt}${cTxt} = 0`
  const steps = [
    `Уравнение вида x² + bx + c = 0. Здесь b = ${n(b)}, c = ${n(c)}. У него обычно два ответа — два корня.`,
  ]
  if (c === 0) {
    steps.push(
      `Свободного числа нет, поэтому выносим x за скобки: x · (x ${sgn(b)}) = 0.`,
      `Произведение равно нулю, когда хотя бы один множитель равен нулю: x = 0 или x ${sgn(b)} = 0.`,
      `Отсюда корни: 0 и ${n(-b)}.`,
    )
  } else {
    steps.push(
      `Теорема Виета: корни — это два числа, у которых сумма равна −b, а произведение равно c. Ищем два числа: сумма = ${n(s)}, произведение = ${n(c)}.`,
      c > 0
        ? `Произведение положительное — значит, оба числа одного знака. Сумма ${s >= 0 ? 'положительная — оба с плюсом' : 'отрицательная — оба с минусом'}.`
        : `Произведение отрицательное — значит, одно число с плюсом, другое с минусом.`,
    )
    const ac = Math.abs(c), pairs: [number, number][] = []
    for (let d = 1; d * d <= ac; d++) if (ac % d === 0) {
      const e = ac / d
      if (c > 0) pairs.push(s >= 0 ? [d, e] : [-d, -e])
      else { pairs.push([d, -e]); if (d !== e) pairs.push([-d, e]) }
    }
    const lines = pairs.map(([x, y]) => `${n(x)} и ${n(y)}: сумма ${n(x + y)}${x + y === s ? ' ✓' : ''}`)
    steps.push(`Переберём пары чисел, дающие в произведении ${n(c)}:\n${lines.join('\n')}`)
    steps.push(`Подходит пара ${n(r1)} и ${n(r2)}. Это и есть корни.`)
    const D = b * b - 4 * c, sq = Math.sqrt(D)
    steps.push(`Если подобрать не получается, есть универсальный способ — дискриминант: D = b² − 4c = ${p(b)}² − 4 × ${p(c)} = ${D}. √D = ${sq}. x = (−b ± √D) : 2 = (${n(s)} ± ${sq}) : 2 → ${n(r2)} и ${n(r1)}.`)
  }
  steps.push(`Проверка: ${n(r1)} + ${p(r2)} = ${n(r1 + r2)} (это −b), ${n(r1)} × ${p(r2)} = ${n(c)} (это c) ✓`)
  return {
    kind: 'quadratic', prompt, answers: [r1, r2], fields: ['Первый корень', 'Второй корень'], steps,
    result: `Корни: ${n(r1)} и ${n(r2)}`,
    hint: c === 0 ? 'Вынесите x за скобки.' : `Подберите два числа: в сумме ${n(s)}, при умножении ${n(c)}.`,
  }
}

// ——— Ряды ———

function sequence(): PracticeTask {
  const t = rnd(0, 4)
  let xs: number[] = []
  const steps: string[] = []
  const diffs = () => xs.slice(1, 5).map((x, i) => x - xs[i])
  if (t === 0) {
    const a = rnd(1, 20), d = rnd(3, 12); xs = Array.from({ length: 6 }, (_, i) => a + i * d)
    steps.push(`Начнём с разностей соседних чисел: ${diffs().map((v, i) => `${xs[i + 1]} − ${xs[i]} = ${v}`).join(', ')}.`, `Разность всегда ${d} — значит, каждый раз прибавляем ${d}.`, `Следующее: ${xs[4]} + ${d} = ${xs[5]}.`)
  } else if (t === 1) {
    const a = rnd(1, 4), q = rnd(2, 3); xs = Array.from({ length: 6 }, (_, i) => a * q ** i)
    steps.push(`Разности: ${diffs().join(', ')} — они растут, одинакового шага нет.`, `Когда числа быстро растут, пробуем делить соседние: ${xs[1]} : ${xs[0]} = ${q}, ${xs[2]} : ${xs[1]} = ${q}, ${xs[3]} : ${xs[2]} = ${q}.`, `Каждое число в ${q} раза больше предыдущего. Следующее: ${xs[4]} × ${q} = ${xs[5]}.`)
  } else if (t === 2) {
    const s0 = rnd(1, 4); xs = Array.from({ length: 6 }, (_, i) => (i + s0) ** 2)
    steps.push(`Разности: ${diffs().join(', ')} — растут на 2 каждый раз. Это признак квадратов.`, `Проверим: ${xs.slice(0, 5).map((x, i) => `${i + s0}² = ${x}`).join(', ')}.`, `Следующее — ${s0 + 5}² = ${xs[5]}.`)
  } else if (t === 3) {
    const a = rnd(1, 3), b = rnd(2, 5); xs = [a, b]; for (let i = 2; i < 6; i++) xs.push(xs[i - 1] + xs[i - 2])
    steps.push(`Разности: ${diffs().join(', ')} — закономерности не видно, и сами разности похожи на числа ряда.`, `Попробуем сложить два соседних: ${xs[0]} + ${xs[1]} = ${xs[2]}, ${xs[1]} + ${xs[2]} = ${xs[3]}, ${xs[2]} + ${xs[3]} = ${xs[4]}. Сработало!`, `Каждое число — сумма двух предыдущих (как ряд Фибоначчи). Следующее: ${xs[3]} + ${xs[4]} = ${xs[5]}.`)
  } else {
    const a = rnd(2, 6); xs = Array.from({ length: 6 }, (_, i) => a + i * (i + 1))
    steps.push(`Разности: ${diffs().join(', ')}.`, `Разности сами растут на 2: следующая разность будет ${xs[5] - xs[4]}.`, `Следующее: ${xs[4]} + ${xs[5] - xs[4]} = ${xs[5]}.`)
  }
  return { kind: 'sequence', prompt: `${xs.slice(0, 5).join(', ')}, ?`, answers: [xs[5]], steps, result: `Следующее число: ${xs[5]}`, hint: 'Посчитайте разности соседних чисел.' }
}

